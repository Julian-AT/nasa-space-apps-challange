def test_producing_commit_refuses_modified_sources(tmp_path: Path) -> None:
    repo = tmp_path / "repo"
    sources = [repo / path for path in PRODUCING_SOURCES]
    for path in sources:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("# committed\n", encoding="utf-8")

    def run(*args: str) -> None:
        subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True)

    run("init", "-q")
    run("add", *PRODUCING_SOURCES)
    run(
        "-c",
        "user.name=t",
        "-c",
        "user.email=t@example.invalid",
        "-c",
        "core.hooksPath=/dev/null",
        "-c",
        "commit.gpgsign=false",
        "commit",
        "-q",
        "-m",
        "sources",
    )
    head = subprocess.run(
        ["git", "-C", str(repo), "rev-parse", "HEAD"], check=True, capture_output=True, text=True
    ).stdout.strip()
    assert terrain.producing_commit(repo) == head
    sources[1].write_text("# edited\n", encoding="utf-8")
    with pytest.raises(terrain.ParityFixtureError, match="commit"):
        terrain.producing_commit(repo)


