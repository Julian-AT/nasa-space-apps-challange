# --- Helpers ----------------------------------------------------------------------------------


def committed_bytes(name: str) -> bytes:
    return (PARITY_DIR / name).read_bytes()


def load(name: str) -> dict[str, Any]:
    document: dict[str, Any] = json.loads(committed_bytes(name).decode("utf-8"))
    return document


def float_tokens(text: str) -> list[str]:
    """Every JSON number token in ``text`` that json reads as a float, in order."""
    tokens: list[str] = []

    def keep(token: str) -> float:
        tokens.append(token)
        return float(token)

    def refuse(token: str) -> float:
        raise AssertionError(f"non-finite JSON constant {token!r}")

    json.loads(text, parse_float=keep, parse_constant=refuse)
    return tokens


def sha256_f8(value: object) -> str:
    """sha256 of an input as little-endian float64 in row-major (C) order."""
    return hashlib.sha256(np.ascontiguousarray(value, dtype="<f8").tobytes()).hexdigest()


def grid_array(rows: list[list[float | None]]) -> FloatArray:
    """A JSON grid with nulls back to float64 with NaN."""
    return np.array([[math.nan if v is None else v for v in row] for row in rows], dtype=np.float64)


def same_bits(a: npt.ArrayLike, b: npt.ArrayLike) -> bool:
    left = np.ascontiguousarray(a, dtype="<f8")
    right = np.ascontiguousarray(b, dtype="<f8")
    return left.shape == right.shape and left.tobytes() == right.tobytes()


def walk(node: object, path: str = "$") -> Iterator[tuple[str, Mapping[str, Any]]]:
    """Every JSON object in ``node`` with its path."""
    if isinstance(node, dict):
        yield path, node
        for key, value in node.items():
            yield from walk(value, f"{path}.{key}")
    elif isinstance(node, list):
        for index, value in enumerate(node):
            yield from walk(value, f"{path}[{index}]")


def git(*args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(REPO), *args], check=True, capture_output=True, text=True
    ).stdout.strip()


def case(name: str) -> dict[str, Any]:
    cases = {item["name"]: item for item in load(TERRAIN_FILE)["cases"]}
    found: dict[str, Any] = cases[name]
    return found


def lookup_of(source: Mapping[str, Any]) -> GeographicLookup:
    spec = source["lookup"]
    assert spec["form"] == "geographic"
    return GeographicLookup(
        origin_lon_deg=spec["origin_lon_deg"],
        origin_lat_deg=spec["origin_lat_deg"],
        pixel_width_deg=spec["pixel_width_deg"],
        pixel_height_deg=spec["pixel_height_deg"],
    )


