@pytest.mark.parametrize("name", TERRAIN_CASES)
def test_fingerprint_values_equal_a_recomputation(name: str) -> None:
    item = case(name)
    config = load_terrain_config()
    grid = window_grid(config.window_m, config.analysis_grid_m)
    values = grid_array(item["resampled"]["values_m"])
    valid = np.array(item["resampled"]["valid"], dtype=np.bool_)
    for rule in ("direction_mean", "pooled_pairs"):
        fingerprint = terrain_fingerprint(
            values,
            valid=valid,
            grid=grid,
            config=config,
            isotropic_rule=rule,
            coarsening_factor=1.0,
        )
        stored = item["fingerprint"][rule]
        assert stored["isotropic_rule"] == rule
        assert stored["valid_cells"] == fingerprint.valid_cells
        assert stored["total_cells"] == fingerprint.total_cells
        assert stored["valid_fraction"] == fingerprint.valid_fraction
        assert stored["excluded_reason"] == fingerprint.excluded_reason
        assert stored["supported_lags_m"] == list(fingerprint.supported_lags_m)
        assert [lag["reason"] for lag in stored["lags"]] == [lag.reason for lag in fingerprint.lags]
        for policy, variant in fingerprint.variants.items():
            record = stored["variants"][policy]
            assert record["name"] == variant.name
            assert record["reason"] == variant.reason
            assert record["nu_m"] == list(variant.nu_m)
            assert record["log_nu"] == [
                None if nu is None or nu == 0.0 else math.log(nu) for nu in variant.nu_m
            ]
            assert record["labels"] == list(variant.labels)
            for direction, nus in variant.directional_nu_m.items():
                assert record["directional_nu_m"][direction] == list(nus)
            assert record["hurst"]["H"] == variant.hurst.H
            assert record["hurst"]["reason"] == variant.hurst.reason
            assert record["hurst"]["label"] == variant.hurst.label


@pytest.mark.parametrize("name", TERRAIN_CASES)
def test_structure_function_equals_a_recomputation(name: str) -> None:
    item = case(name)
    document = load(TERRAIN_FILE)
    lags = document["structure_lags_m"]
    diagonal = math.hypot(90.0, 90.0)
    assert lags == sorted({*document["config"]["lags_m"], *(k * diagonal for k in (3, 4, 6, 8))})
    values = grid_array(item["resampled"]["values_m"])
    valid = np.array(item["resampled"]["valid"], dtype=np.bool_)
    for rule in ("direction_mean", "pooled_pairs"):
        result = structure_function(
            values, valid=valid, spacing_m=90.0, lags_m=lags, isotropic_rule=rule
        )
        stored = item["structure"][rule]
        assert stored["isotropic_rule"] == rule
        assert stored["lags_m"] == lags
        for direction, entries in result.directional.items():
            for entry, record in zip(entries, stored["directional"][direction], strict=True):
                assert record["nu_m"] == entry.nu_m
                assert record["pair_count"] == entry.pair_count
                assert record["reason"] == entry.reason
                assert record["offset_cells"] == (
                    None if entry.offset_cells is None else list(entry.offset_cells)
                )
        for summary, record in zip(result.isotropic, stored["isotropic"], strict=True):
            assert record["nu_m"] == summary.nu_m
            assert record["directions"] == list(summary.directions)
            assert record["reason"] == summary.reason


