# --- Machine-readable reasons; unavailable is null, never 0 -----------------------------------


def test_every_reason_is_a_t3_machine_readable_string() -> None:
    allowed = (
        DIRECTIONAL_REASONS
        | ISOTROPIC_REASONS
        | LAG_REASONS
        | WINDOW_REASONS
        | VARIANT_REASONS
        | HURST_REASONS
    )
    seen: set[str] = set()
    for path, node in walk(load(TERRAIN_FILE)):
        for key in ("reason", "excluded_reason"):
            if key in node and node[key] is not None:
                assert node[key] in allowed, (path, node[key])
                seen.add(node[key])
    # The cases reach reasons of every kind: off-grid lags, window exclusion, the H gate.
    assert {"axis_lag_not_on_grid", "diagonal_lag_not_on_grid"} <= seen
    assert {"below_min_valid_fraction", "window_excluded"} <= seen


def test_lag_reasons_are_lag_strings_and_hurst_reasons_are_hurst_strings() -> None:
    for item in load(TERRAIN_FILE)["cases"]:
        for rule, fingerprint in item["fingerprint"].items():
            assert fingerprint["excluded_reason"] in WINDOW_REASONS | {None}
            for lag in fingerprint["lags"]:
                assert lag["reason"] in LAG_REASONS | {None}, (item["name"], rule)
            for variant in fingerprint["variants"].values():
                assert variant["reason"] in VARIANT_REASONS | {None}
                assert variant["hurst"]["reason"] in HURST_REASONS | {None}
        for structure in item["structure"].values():
            for entries in structure["directional"].values():
                assert all(e["reason"] in DIRECTIONAL_REASONS | {None} for e in entries)
            assert all(e["reason"] in ISOTROPIC_REASONS | {None} for e in structure["isotropic"])


def test_unavailable_values_are_null_never_zero() -> None:
    document = load(TERRAIN_FILE)
    for item in document["cases"]:
        stored = item["resampled"]
        for row_values, row_valid in zip(stored["values_m"], stored["valid"], strict=True):
            for value, ok in zip(row_values, row_valid, strict=True):
                assert (value is None) == (not ok)
        for structure in item["structure"].values():
            entries = [e for es in structure["directional"].values() for e in es]
            for entry in [*entries, *structure["isotropic"]]:
                if entry["reason"] is not None:
                    assert entry["nu_m"] is None
                    assert entry["log_nu"] is None
                    assert entry["pair_count"] == 0
                else:
                    assert entry["nu_m"] is not None and entry["pair_count"] > 0
                    assert (entry["log_nu"] is None) == (entry["nu_m"] == 0.0)
        for fingerprint in item["fingerprint"].values():
            for lag in fingerprint["lags"]:
                assert (lag["reason"] is None) == (lag["pair_count"] > 0)
            for variant in fingerprint["variants"].values():
                supported = [lag["reason"] is None for lag in fingerprint["lags"]]
                for nu, log_nu, ok, label in zip(
                    variant["nu_m"], variant["log_nu"], supported, variant["labels"], strict=True
                ):
                    assert (nu is None) == (not ok or variant["reason"] is not None)
                    assert label == ("Unavailable" if nu is None else "Derived")
                    assert (log_nu is None) == (nu is None or nu == 0.0)
                hurst = variant["hurst"]
                assert (hurst["H"] is None) == (hurst["reason"] is not None)
                assert (hurst["log_intercept"] is None) == (hurst["H"] is None)
                assert hurst["label"] == ("Unavailable" if hurst["H"] is None else "Derived")
                if variant["reason"] is not None:
                    assert variant["plane"] is None
                    assert variant["structure"] is None


