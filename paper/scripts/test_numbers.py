def test_json_pointer_follows_rfc_6901(tmp_path: Path) -> None:
    bundle = make_bundle(tmp_path, {"a/b": {"m~n": [0.5, 2.25]}})
    status, out = run(tmp_path / "numbers.tex", bundle, (macro(pointer="/a~1b/m~0n/1"),))
    assert status == 0
    assert out.read_text(encoding="ascii").endswith("\\newcommand{\\TestValue}{2.250}\n")


def test_macros_are_written_in_spec_order(tmp_path: Path) -> None:
    bundle = make_bundle(tmp_path, {"a": 1, "b": 2})
