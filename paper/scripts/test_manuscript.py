# --- Rule 6: generated files --------------------------------------------------------------------

NEWCOMMAND = re.compile(r"\\newcommand\{\\[A-Za-z]+\}\{[^{}\n]+\}")


def generated_file_problems(name: str, text: str) -> list[str]:
    problems = []
    first = text.split("\n", 1)[0]
    if GENERATED_HEADER.fullmatch(first) is None:
        problems.append(f"first line is not a generated-file comment: {first!r}")
    if name == "numbers.tex":
        if first != NUMBERS_HEADER:
            problems.append("numbers.tex does not name numbers.py")
        problems += [
            f"not a comment or \\newcommand line: {line!r}"
            for line in text.split("\n")[:-1]
            if not line.startswith("%") and NEWCOMMAND.fullmatch(line) is None
        ]
    if "\r" in text or not text.endswith("\n"):
        problems.append("not LF-terminated")
    return problems


@pytest.mark.parametrize(
    ("name", "text"),
    [
        ("numbers.tex", NUMBERS_HEADER + "\n% Source: no release bundle was read.\n"),
        ("numbers.tex", NUMBERS_HEADER + "\n% Source.\n\\newcommand{\\MoonRecall}{0.93}\n"),
        ("table.tex", TABLE_HEADER + "\n"),
    ],
)
def test_generated_file_rule_passes(name: str, text: str) -> None:
    assert generated_file_problems(name, text) == []


@pytest.mark.parametrize(
    ("name", "text"),
    [
        ("numbers.tex", "\\newcommand{\\A}{1}\n"),
        ("numbers.tex", "% Generated by hand.\n"),
        ("numbers.tex", TABLE_HEADER + "\n"),
        ("numbers.tex", NUMBERS_HEADER + "\n\\def\\A{1}\n"),
        ("numbers.tex", NUMBERS_HEADER + "\n\\newcommand{\\A1}{1}\n"),
        ("numbers.tex", NUMBERS_HEADER + "\n\\newcommand{\\A}{}\n"),
        ("numbers.tex", NUMBERS_HEADER + "\n\n"),
        ("numbers.tex", NUMBERS_HEADER + "\n\\renewcommand{\\A}{1}\n"),
        ("numbers.tex", NUMBERS_HEADER + "\r\n"),
        ("numbers.tex", NUMBERS_HEADER),
        ("table.tex", "\\begin{tabular}{l}\\end{tabular}\n"),
    ],
)
def test_generated_file_rule_fails(name: str, text: str) -> None:
    assert generated_file_problems(name, text) != []


def test_generated_files_carry_their_comment() -> None:
    generated = sorted(path for path in (PAPER / "generated").iterdir() if path.is_file())
    assert "numbers.tex" in [path.name for path in generated]
    found = {
        path.name: problems
        for path in generated
        if (problems := generated_file_problems(path.name, path.read_bytes().decode("utf-8")))
    }
    assert found == {}
