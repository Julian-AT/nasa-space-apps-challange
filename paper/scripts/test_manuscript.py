# --- Rule 3: no literal measurements ------------------------------------------------------------


def literal_digits(text: str) -> list[tuple[int, str]]:
    """(line, text) of each line with a digit outside comments and key command arguments."""
    lines = blank_key_arguments(text).splitlines()
    return [(n, line.strip()) for n, line in enumerate(lines, start=1) if re.search(r"\d", line)]


