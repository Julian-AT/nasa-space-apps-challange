def test_raster_image_rule_finds_every_raster_suffix(tmp_path: Path) -> None:
    for suffix in sorted(RASTER_SUFFIXES):
        (tmp_path / "nested").mkdir(exist_ok=True)
        (tmp_path / "nested" / f"image{suffix.upper()}").write_bytes(b"")
