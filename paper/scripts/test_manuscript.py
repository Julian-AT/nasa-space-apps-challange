# Commands whose arguments are keys, labels or paths rather than text.
KEY_COMMAND = re.compile(r"\\(?:ref|eqref|label|input|[Cc]ite[A-Za-z]*)(?![A-Za-z])\*?")
# Formatting commands whose argument is text that counts towards the abstract.
TEXT_WRAPPERS = frozenset(
    {"emph", "textit", "textbf", "textsc", "textrm", "textsf", "texttt", "textsl", "mbox", "text"}
)


# --- LaTeX helpers ------------------------------------------------------------------------------


def strip_comments(text: str) -> str:
    """Remove each unescaped % up to the end of its line, keeping the line break."""
    out: list[str] = []
    i = 0
    while i < len(text):
        char = text[i]
        if char == "\\":
            out.append(text[i : i + 2])
            i += 2
        elif char == "%":
            end = text.find("\n", i)
            if end == -1:
                break
            i = end
        else:
            out.append(char)
            i += 1
    return "".join(out)


def group_end(text: str, start: int) -> int:
    """Index just past the brace group that opens at text[start] == '{'."""
    depth = 0
    i = start
    while i < len(text):
        char = text[i]
        if char == "\\":
            i += 2
            continue
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    raise ValueError(f"unbalanced braces from offset {start}")


OPTIONAL_ARGUMENT = re.compile(r"\s*\[[^\]]*\]")
OPENING_BRACE = re.compile(r"\s*\{")


def arguments_end(text: str, start: int) -> int:
    """Index past the optional [..] arguments and the one {..} argument that follow start."""
    i = start
    while (match := OPTIONAL_ARGUMENT.match(text, i)) is not None:
        i = match.end()
    match = OPENING_BRACE.match(text, i)
    return i if match is None else group_end(text, match.end() - 1)


def blank_key_arguments(text: str) -> str:
    """Comment-free text with each key command and its arguments blanked, keeping line breaks."""
    text = strip_comments(text)
    out: list[str] = []
    i = 0
    for match in KEY_COMMAND.finditer(text):
        if match.start() < i:
            continue
        end = arguments_end(text, match.end())
        out.append(text[i : match.start()])
        out.append(re.sub(r"[^\n]", " ", text[match.start() : end]))
        i = end
    out.append(text[i:])
    return "".join(out)


# --- Rule 1: section and appendix titles --------------------------------------------------------

STRUCTURE = re.compile(
    r"\\(?:(?P<appendix>appendix)|(?P<input>input)|(?P<section>section)\s*(?P<star>\*)?)"
    r"(?![A-Za-z])"
)


def structure(text: str, read: Callable[[str], str], depth: int = 0) -> Iterator[tuple[str, str]]:
    """('section', title) and ('appendix', '') in include order, following \\input."""
    if depth > 8:
        raise ValueError("\\input nesting deeper than 8")
    text = strip_comments(text)
    for match in STRUCTURE.finditer(text):
        if match["appendix"]:
            yield ("appendix", "")
            continue
        brace = re.compile(r"\s*(?:\[[^\]]*\]\s*)?\{").match(text, match.end())
        if brace is None:
            continue
        end = group_end(text, brace.end() - 1)
        argument = text[brace.end() : end - 1].strip()
        if match["input"]:
            yield from structure(read(argument), read, depth + 1)
        elif not match["star"]:
            # Starred sections are unnumbered (acknowledgements, AI-use statement) and are not
            # part of the 22.2 numbering.
            yield ("section", argument)


def titles(text: str, read: Callable[[str], str]) -> tuple[list[str], list[str]]:
    """Section titles before \\appendix and appendix titles after it."""
    main: list[str] = []
    appendix: list[str] = []
    current = main
    for kind, title in structure(text, read):
        if kind == "appendix":
            current = appendix
        else:
            current.append(title)
    return main, appendix


def titles_follow_prd(main: list[str], appendix: list[str]) -> bool:
    return main == list(MAIN_TITLES) and appendix in (
        list(APPENDIX_TITLES),
        [*APPENDIX_TITLES, OPTIONAL_THIRD_APPENDIX],
    )


def read_from(files: dict[str, str]) -> Callable[[str], str]:
    def read(name: str) -> str:
        return files[name if name.endswith(".tex") else f"{name}.tex"]

    return read


def read_paper(name: str) -> str:
    path = PAPER / (name if name.endswith(".tex") else f"{name}.tex")
    return path.read_text(encoding="utf-8")


def as_inputs(sections: list[str], appendices: list[str]) -> tuple[str, dict[str, str]]:
    files = {f"s{n}.tex": f"\\section{{{title}}}\n" for n, title in enumerate(sections)}
    files |= {f"a{n}.tex": f"\\section{{{title}}}\n" for n, title in enumerate(appendices)}
    main = "".join(f"\\input{{s{n}}}\n" for n in range(len(sections)))
    main += "\\appendix\n" + "".join(f"\\input{{a{n}}}\n" for n in range(len(appendices)))
    return main, files


@pytest.mark.parametrize(
    ("appendices", "passes"),
    [
        (list(APPENDIX_TITLES), True),
        ([*APPENDIX_TITLES, OPTIONAL_THIRD_APPENDIX], True),
        ([OPTIONAL_THIRD_APPENDIX, *APPENDIX_TITLES], False),
        ([APPENDIX_TITLES[0], OPTIONAL_THIRD_APPENDIX, APPENDIX_TITLES[1]], False),
        (list(APPENDIX_TITLES)[:1], False),
        ([*APPENDIX_TITLES, "Extra"], False),
    ],
)
def test_title_rule_on_appendix_lists(appendices: list[str], passes: bool) -> None:
    main, files = as_inputs(list(MAIN_TITLES), appendices)
    assert titles_follow_prd(*titles(main, read_from(files))) is passes


@pytest.mark.parametrize(
    "sections",
    [
        list(MAIN_TITLES)[1:],
        [MAIN_TITLES[1], MAIN_TITLES[0], *MAIN_TITLES[2:]],
        [*MAIN_TITLES, "Discussion"],
        ["Introduction to terrain", *MAIN_TITLES[1:]],
    ],
    ids=["missing", "swapped", "extra", "renamed"],
)
def test_title_rule_fails_on_wrong_sections(sections: list[str]) -> None:
    main, files = as_inputs(sections, list(APPENDIX_TITLES))
    assert not titles_follow_prd(*titles(main, read_from(files)))


