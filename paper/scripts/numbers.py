# What a format may produce: a plain decimal number, optionally with digit grouping or exponent.
PLAIN_NUMBER = re.compile(r"[-+]?[0-9][0-9,]*(?:\.[0-9]+)?(?:[eE][-+]?[0-9]+)?")


@dataclass(frozen=True)
class Macro:
    r"""One number macro: \<name> is the number at `pointer` in the bundle file `file`.

    name: ASCII letters only. file: bundle-relative path listed in manifest.json, for example
    report/probes.json. pointer: a JSON pointer (RFC 6901). format_spec: a Python format
    specification such as ".3f".
    """

    name: str
    file: str
    pointer: str
    format_spec: str


# Empty until a release bundle with results exists.
MACROS: tuple[Macro, ...] = ()


@dataclass(frozen=True)
class ArtifactMacro:
    r"""One macro read from a committed artifact in the repository working tree.

    path: repository-relative JSON file, for example outputs/g0/earth-radar-roi.json. pointer: a
    JSON pointer. format_spec: a Python format specification for a number, the same prefixed
    with % for a fraction shown in percent, "count" for the length of an array or object, or
    "text" for a string, which is escaped for LaTeX, or min:, max:, median: or span: (max minus
    min) followed by a number format for an aggregate over a pointer with one "/*" segment, such
    as /*/distance (n: counts the non-null values). A leading "?" makes an absent pointer
    render \\NotAvailable instead of failing; it is only for artifacts whose schema is not fixed.

    An artifact that does not exist yet, or a null value (missing evidence), renders as
    \NotAvailable, never as 0. A pointer that is absent from an existing file, a non-finite
    number or a value of the wrong type is an error, because it is a spec bug, not a missing
    result. Each artifact read is named with its SHA-256 in a comment line.
    """

    name: str
    path: str
    pointer: str
    format_spec: str


