class MacroError(Exception):
    """A macro whose value cannot be read or rendered."""


def spec_errors(macros: Sequence[Macro | ArtifactMacro]) -> list[str]:
    errors = []
    seen: set[str] = set()
    for macro in macros:
        if NAME.fullmatch(macro.name) is None:
            errors.append(f"macro name {macro.name!r} is not ASCII letters only")
        elif macro.name in seen:
            errors.append(f"\\{macro.name}: the name is listed twice")
        seen.add(macro.name)
    return errors


def resolve(document: object, pointer: str) -> object:
    """The value at a JSON pointer (RFC 6901); an absent key or index is an error."""
    if pointer == "":
        return document
    if not pointer.startswith("/"):
        raise MacroError(f"pointer {pointer!r} does not start with /")
    value = document
    for raw in pointer[1:].split("/"):
        if BAD_ESCAPE.search(raw):
            raise MacroError(f"pointer {pointer!r} has an escape other than ~0 or ~1")
        token = raw.replace("~1", "/").replace("~0", "~")
        if isinstance(value, dict):
            if token not in value:
                raise MacroError(f"pointer {pointer!r}: no key {token!r}")
            value = value[token]
        elif isinstance(value, list):
            if ARRAY_INDEX.fullmatch(token) is None or int(token) >= len(value):
                raise MacroError(f"pointer {pointer!r}: no array index {token!r}")
            value = value[int(token)]
        else:
            raise MacroError(f"pointer {pointer!r}: cannot index into {type(value).__name__}")
    return value


def render(value: object, format_spec: str) -> str:
    if value is None:
        raise MacroError("the value is null")
    if isinstance(value, bool) or not isinstance(value, int | float):
        raise MacroError(f"the value {value!r} is not a number")
    if not math.isfinite(value):
        raise MacroError(f"the value {value!r} is not finite")
    try:
        text = format(value, format_spec)
    except (TypeError, ValueError) as error:
        raise MacroError(f"format {format_spec!r} fails on {value!r}: {error}") from None
    if PLAIN_NUMBER.fullmatch(text) is None:
        raise MacroError(f"format {format_spec!r} gives {text!r}, which is not a plain number")
    return text


def unique_keys(pairs: list[tuple[str, object]]) -> dict[str, object]:
    keys = [key for key, _ in pairs]
    duplicates = sorted({key for key in keys if keys.count(key) > 1})
    if duplicates:
        raise MacroError(f"duplicate JSON keys {duplicates}")
    return dict(pairs)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def bundle_lines(bundle: Path, macros: Sequence[Macro]) -> tuple[list[str], list[str]]:
    """(source and macro lines, errors) for a release bundle."""
    # Imported here so that the run without a bundle does not need the pipeline package.
    from terraluna_pipeline.export import validate_bundle
    from terraluna_pipeline.schema import BundleManifest

    errors = [str(error) for error in validate_bundle(bundle, production=True)]
    if errors:
        return [], errors
    manifest_bytes = (bundle / "manifest.json").read_bytes()
    manifest = BundleManifest.model_validate_json(manifest_bytes)
    listed = {entry.path: entry.sha256 for entry in manifest.files}
    lines = [
        f"% Source: release bundle {manifest.bundle_version}, "
        f"manifest.json sha256 {sha256(manifest_bytes)}."
    ]
    documents: dict[str, object] = {}
    for macro in macros:
        try:
            if macro.file not in listed:
                raise MacroError(f"{macro.file} is not listed in manifest.json")
            if macro.file not in documents:
                data = (bundle / macro.file).read_bytes()
                if sha256(data) != listed[macro.file]:
                    raise MacroError(f"{macro.file} changed after the bundle was validated")
                try:
                    documents[macro.file] = json.loads(data, object_pairs_hook=unique_keys)
                except (UnicodeDecodeError, json.JSONDecodeError) as error:
                    raise MacroError(f"{macro.file} is not JSON: {error}") from None
            value = render(resolve(documents[macro.file], macro.pointer), macro.format_spec)
        except MacroError as error:
            errors.append(f"\\{macro.name}: {macro.file}#{macro.pointer}: {error}")
            continue
        lines.append(f"\\newcommand{{\\{macro.name}}}{{{value}}}")
    return lines, errors


def escape_text(value: str) -> str:
    return "".join(LATEX_SPECIAL.get(char, char) for char in value)


AGGREGATES = ("min:", "max:", "median:", "n:", "span:")


SELECTOR = re.compile(r"/\[([^\]]+)\]")


def matches(item: object, conditions: str) -> bool:
    """key=value compares str(field) exactly; key^=prefix compares the start of str(field)."""
    if not isinstance(item, dict):
        return False
    for part in conditions.split(","):
        if "^=" in part:
            key, prefix = part.split("^=", 1)
            if not str(item.get(key)).startswith(prefix):
                return False
        else:
            key, value = part.split("=", 1)
            if str(item.get(key)) != value:
                return False
    return True


def select(document: object, pointer: str) -> object:
    """Resolve a pointer with "[key=value,...]" segments.

    "[...]" picks the one array element whose fields match; zero or several matches are an
    error, so a selector never picks an element silently. "[*...]" keeps every match (at least
    one) and maps the rest of the pointer over them, giving an array for min:, max: or median:.
    """
    match = SELECTOR.search(pointer)
    if match is None:
        return resolve_star(document, pointer)
    items = resolve(document, pointer[: match.start()])
    if not isinstance(items, list):
        raise MacroError(f"pointer {pointer!r}: the selector needs an array")
    conditions = match.group(1)
    many = conditions.startswith("*")
    hits = [item for item in items if matches(item, conditions.removeprefix("*"))]
    rest = pointer[match.end() :]
    if many:
        if not hits:
            raise MacroError(f"pointer {pointer!r}: no element matches {conditions}")
        return [select(hit, rest) for hit in hits]
    if len(hits) != 1:
        raise MacroError(f"pointer {pointer!r}: {len(hits)} elements match {conditions}")
    return select(hits[0], rest)


def resolve_artifact(document: object, pointer: str) -> object:
    """resolve(), plus "[key=value]" selectors and one "/*" segment mapped over an array."""
    return select(document, pointer)


def resolve_star(document: object, pointer: str) -> object:
    """resolve(), plus one "/*" segment that maps the rest of the pointer over an array."""
    if "/*" not in pointer:
        return resolve(document, pointer)
    head, _, rest = pointer.partition("/*")
    items = resolve(document, head)
    if not isinstance(items, list):
        raise MacroError(f"pointer {pointer!r}: {head!r} is not an array")
    return [resolve(item, rest) for item in items]


def aggregate(values: object, format_spec: str) -> str:
    """min, max, median (the mean of the two middle values) or count n of an array of numbers."""
    name, _, spec = format_spec.partition(":")
    if not isinstance(values, list) or not values:
        raise MacroError(f"{name} needs a non-empty array, got {values!r}")
    numbers = []
    # Null entries are missing values: they are skipped, never read as 0, and "n:" counts the rest.
    for value in (value for value in values if value is not None):
        if (
            isinstance(value, bool)
            or not isinstance(value, int | float)
            or not math.isfinite(value)
        ):
            raise MacroError(f"{name}: {value!r} is not a finite number")
        numbers.append(float(value))
    if name == "n":
        return render(len(numbers), spec)
    if not numbers:
        return NOT_AVAILABLE
    numbers.sort()
    middle = len(numbers) // 2
    result = {
        "min": numbers[0],
        "max": numbers[-1],
        "n": float(len(numbers)),
        "span": numbers[-1] - numbers[0],
        "median": numbers[middle]
        if len(numbers) % 2
        else (numbers[middle - 1] + numbers[middle]) / 2,
    }[name]
    return render(result, spec)


def render_artifact(value: object, format_spec: str) -> str:
    if value is None:
        return NOT_AVAILABLE
    if format_spec.startswith(AGGREGATES):
        return aggregate(value, format_spec)
    if format_spec == "text":
        if not isinstance(value, str) or not value.strip():
            raise MacroError(f"the value {value!r} is not a non-empty string")
        return escape_text(value)
    if format_spec == "count":
        if not isinstance(value, list | dict):
            raise MacroError(f"the value {value!r} is not an array or object")
        return str(len(value))
    if format_spec.startswith("list:"):
        # An array of numbers written as "a, b and c".
        if not isinstance(value, list) or not value:
            raise MacroError(f"the value {value!r} is not a non-empty array")
        items = [render(item, format_spec[5:]) for item in value]
        return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]
    if format_spec.startswith("%"):
        # A fraction shown in percent: the value times 100, under the rest of the spec.
        if isinstance(value, bool) or not isinstance(value, int | float):
            raise MacroError(f"the value {value!r} is not a number")
        return render(value * 100, format_spec[1:])
    return render(value, format_spec)


def parse_artifact(path: str, data: bytes) -> object:
    """A JSON artifact, or a YAML file such as config/run.yaml (safe loader only)."""
    if path.endswith((".yaml", ".yml")):
        import yaml

        try:
            return yaml.safe_load(data.decode("utf-8"))
        except (UnicodeDecodeError, yaml.YAMLError) as error:
            raise MacroError(f"{path} is not YAML: {error}") from None
    try:
        return json.loads(data, object_pairs_hook=unique_keys)
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise MacroError(f"{path} is not JSON: {error}") from None


def artifact_lines(
    root: Path, macros: Sequence[ArtifactMacro]
) -> tuple[list[str], list[str], list[str]]:
    """(source comment lines, macro lines, errors) for macros read from repository artifacts."""
    sources: dict[str, str] = {}
    documents: dict[str, object] = {}
    lines: list[str] = []
    errors: list[str] = []
    absent: list[str] = []
    for macro in macros:
        path = root / macro.path
        try:
            if macro.path not in sources:
                if not path.is_file():
                    sources[macro.path] = f"% Artifact {macro.path}: not present."
                else:
                    data = path.read_bytes()
                    sources[macro.path] = f"% Artifact {macro.path} sha256 {sha256(data)}."
                    documents[macro.path] = parse_artifact(macro.path, data)
            spec = macro.format_spec
            # "?" marks a macro whose producer has not fixed its schema yet: an absent pointer in
            # an existing file then renders \NotAvailable and is named in a comment line.
            optional = spec.startswith("?")
            spec = spec.removeprefix("?")
            if macro.path in documents:
                try:
                    found = resolve_artifact(documents[macro.path], macro.pointer)
                except MacroError:
                    if not optional:
                        raise
                    absent.append(f"% Artifact {macro.path}: pointer {macro.pointer} absent.")
                    found = None
                value = render_artifact(found, spec)
            else:
                value = NOT_AVAILABLE
        except MacroError as error:
            errors.append(f"\\{macro.name}: {macro.path}#{macro.pointer}: {error}")
            continue
        lines.append(f"\\newcommand{{\\{macro.name}}}{{{value}}}")
    return list(sources.values()) + absent, lines, errors


def write_atomic(path: Path, text: str) -> None:
    """Replace path with text in one step, so a failed run never leaves a partial file."""
    fd, temporary = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(text.encode("utf-8"))
        os.chmod(temporary, 0o644)
        os.replace(temporary, path)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise


def main(
    argv: Sequence[str] | None = None,
    macros: Sequence[Macro] = MACROS,
    artifacts: Sequence[ArtifactMacro] = ARTIFACT_MACROS,
    root: Path = ROOT,
) -> int:
    parser = argparse.ArgumentParser(description="Write the generated number macros.")
    parser.add_argument("--bundle", type=Path, help="release bundle directory to read")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output .tex file")
    args = parser.parse_args(argv)
    out: Path = args.out

    errors = spec_errors([*macros, *artifacts])
    lines = [HEADER]
    if args.bundle is None:
        if macros:
            errors.append(f"{len(macros)} macros need a release bundle: set BUNDLE_VERSION")
        lines.append(NO_BUNDLE_SOURCE)
    else:
        body, bundle_errors = bundle_lines(args.bundle, macros)
        errors += bundle_errors
        lines += body
    artifact_sources, artifact_macros, artifact_errors = artifact_lines(root, artifacts)
    errors += artifact_errors
    lines += artifact_sources + artifact_macros
    if errors:
        for error in errors:
            print(f"numbers.py: {error}", file=sys.stderr)
        print(f"numbers.py: {len(errors)} errors; {out} is unchanged", file=sys.stderr)
        return 1
    write_atomic(out, "\n".join(lines) + "\n")
    print(f"numbers.py: wrote {out} with {len(macros) + len(artifacts)} macros")
    return 0


if __name__ == "__main__":
    if not sys.flags.safe_path:
        sys.exit("numbers.py: run it with python -P so that it cannot shadow the numbers module")
    sys.exit(main())
