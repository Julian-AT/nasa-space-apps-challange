"""Write paper/generated/numbers.tex, the number macros of the paper (PRD 22.6, D10, D34).

Without --bundle the file holds only its two comment lines. With --bundle <dir>, the release
bundle is first validated in production mode, then each MACROS entry reads one number from a JSON
file listed in the manifest, by JSON pointer (RFC 6901). Any error stops the run with exit 1: every
error is printed and the output file is left unchanged. A missing value is an error, never 0 or an
empty macro.

Run it with python -P, as the Makefile does. Otherwise this file's directory comes first on
sys.path and the file would shadow the standard library module numbers.
"""

