"""The reference record of the paper and the refs.bib generated from it (PRD 22.4, 22.6 check 3).

paper/reference-verification.json holds one record per reference, verified at a primary source
(publisher, arXiv, NASA ADS or the data provider). `references.py check` validates the record.
`references.py bib` writes refs.bib for exactly the keys the manuscript cites; a cited key that is
missing or unresolved is an error, so an unverified or uncited entry can never reach the PDF.
"""

from __future__ import annotations

import argparse
import datetime
import re
import sys
from collections.abc import Iterable, Sequence
from pathlib import Path
from typing import Literal
from urllib.parse import urlsplit

from pydantic import BaseModel, ConfigDict, ValidationError

PAPER = Path(__file__).resolve().parents[1]
RECORD = PAPER / "reference-verification.json"
BIB = PAPER / "refs.bib"
BIB_HEADER = (
    "% Generated by paper/scripts/references.py from reference-verification.json. "
    "Do not edit; run make -C paper bib."
)

KEY = re.compile(r"[a-z]+[0-9]{4}[a-z]*")
DOI = re.compile(r"10\.\d{4,9}/\S+")
EPRINT = re.compile(r"\d{4}\.\d{4,5}")
ADS_PREFIX = "https://ui.adsabs.harvard.edu/abs/"
CROSSREF_PREFIX = "https://api.crossref.org/works/"
# Fixed BibTeX field order of the generated entries; also the set of allowed field names.
FIELD_ORDER = (
    "author",
    "editor",
    "title",
    "journal",
    "booktitle",
    "year",
    "month",
    "volume",
    "number",
    "pages",
    "publisher",
    "institution",
    "school",
    "howpublished",
    "doi",
    "eprint",
    "archiveprefix",
    "primaryclass",
    "url",
    "note",
)
FIELDS = frozenset(FIELD_ORDER)
LOCATION = re.compile(r"(?i)\s*(page|pages|p\.|section|sec\.|figure|fig\.|table|abstract)\b")
SECONDARY_HOSTS = (
    "typeset.io",
    "unpaywall.org",
    "doaj.org",
    "researchgate.net",
    "semanticscholar.org",
    "scholar.google.com",
    "wikipedia.org",
    "academia.edu",
    "eos.org",
    "experts.arizona.edu",
    "jrskok.com",
)
# \cite, \citet, \citep, \citealt, \citealp, \citeauthor, \citeyear and starred forms, with an
# optional pre- and post-note.
CITE = re.compile(
    r"\\cite(?:t|p|alt|alp|author|year)?\*?(?:\s*\[[^\]]*\]){0,2}\s*\{([^}]*)\}",
)
COMMENT = re.compile(r"(?<!\\)%.*")


class Support(BaseModel):
    model_config = ConfigDict(extra="forbid")
    claim: str
    location: str


class Reference(BaseModel):
    model_config = ConfigDict(extra="forbid")
    status: Literal["verified", "unresolved"]
    unresolvedReason: str | None
    entryType: Literal[
        "article", "inproceedings", "misc", "techreport", "phdthesis", "book", "incollection"
    ]
    fields: dict[str, str]
    primaryUrl: str
    sourceKind: Literal["publisher", "arxiv", "ads", "provider"]
    metadataUrl: str | None
    searchQuery: str
    checked: datetime.date
    verifiedFields: list[str]
    evidence: str
    abstract: str | None
    abstractSource: str | None
    abstractUnavailableReason: str | None
    supports: list[Support]


class Record(BaseModel):
    model_config = ConfigDict(extra="forbid")
    method: str
    references: dict[str, Reference]


def balanced(value: str) -> bool:
    depth = 0
    escaped = False
    for char in value:
        if escaped:
            escaped = False
        elif char == "\\":
            escaped = True
        elif char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth < 0:
                return False
    return depth == 0


def secondary(url: str | None) -> bool:
    if url is None:
        return False
    host = (urlsplit(url).hostname or "").lower()
    return any(host == bad or host.endswith("." + bad) for bad in SECONDARY_HOSTS)


def reference_errors(key: str, ref: Reference) -> list[str]:
    """Every rule violation of one record, as 'key: field: message'."""
    errors: list[str] = []

    def err(field: str, message: str) -> None:
        errors.append(f"{key}: {field}: {message}")

    if KEY.fullmatch(key) is None:
        err("key", "does not match ^[a-z]+[0-9]{4}[a-z]*$")
    for name, value in ref.fields.items():
        if name not in FIELDS:
            err(f"fields.{name}", "is not an allowed BibTeX field")
        if not value.strip():
            err(f"fields.{name}", "is empty")
        if not balanced(value):
            err(f"fields.{name}", "has unbalanced braces")
    if ref.status == "verified":
        for name in ("author", "title", "year"):
            if name not in ref.fields:
                err(f"fields.{name}", "is required for a verified record")
        if set(ref.verifiedFields) != set(ref.fields) or len(ref.verifiedFields) != len(
            set(ref.verifiedFields)
        ):
            err("verifiedFields", "must list exactly the keys of fields")
        if not ref.supports:
            err("supports", "a verified record needs at least one supports entry")
        for index, support in enumerate(ref.supports):
            if not support.claim.strip():
                err(f"supports[{index}].claim", "is empty")
            if LOCATION.match(support.location) is None:
                err(
                    f"supports[{index}].location",
                    "is not a page, section, figure, table or abstract",
                )
        if ref.unresolvedReason is not None:
            err("unresolvedReason", "must be null for a verified record")
        if not ref.evidence.strip():
            err("evidence", "is empty")
    elif not (ref.unresolvedReason or "").strip():
        err("unresolvedReason", "an unresolved record needs a reason")

    doi = ref.fields.get("doi")
    eprint = ref.fields.get("eprint")
    if doi is not None:
        if DOI.fullmatch(doi) is None:
            err("fields.doi", "does not match ^10\\.\\d{4,9}/\\S+$")
        if ref.primaryUrl != f"https://doi.org/{doi}":
            err("primaryUrl", f"must be https://doi.org/{doi}")
        if ref.sourceKind not in ("publisher", "provider"):
            err("sourceKind", "a record with a doi is publisher (or provider for a data product)")
    elif eprint is not None:
        if EPRINT.fullmatch(eprint) is None:
            err("fields.eprint", "is not a new-style arXiv id without version")
        if ref.fields.get("archiveprefix") != "arXiv":
            err("fields.archiveprefix", "must be arXiv with an eprint")
        if ref.primaryUrl != f"https://arxiv.org/abs/{eprint}":
            err("primaryUrl", f"must be https://arxiv.org/abs/{eprint}")
        if ref.sourceKind != "arxiv":
            err("sourceKind", "a record with an eprint and no doi is arxiv")
    elif ref.sourceKind in ("publisher", "arxiv"):
        err("sourceKind", f"{ref.sourceKind} needs a doi or an eprint")
    if ref.sourceKind == "ads" and not ref.primaryUrl.startswith(ADS_PREFIX):
        err("primaryUrl", f"an ads record needs a {ADS_PREFIX} URL")
    if not ref.primaryUrl.startswith("https://"):
        err("primaryUrl", "is not https")

    for name, url in (
        ("primaryUrl", ref.primaryUrl),
        ("metadataUrl", ref.metadataUrl),
        ("abstractSource", ref.abstractSource),
    ):
        if secondary(url):
            err(name, f"{url} is a secondary host")

    if ref.status == "verified":
        if ref.sourceKind in ("publisher", "arxiv", "ads"):
            if not (ref.abstract or "").strip():
                err("abstract", "a verified publisher, arxiv or ads record needs its abstract")
            if not (ref.abstractSource or "").startswith("https://"):
                err("abstractSource", "needs an https source")
        elif ref.abstract is None and not (ref.abstractUnavailableReason or "").strip():
            err("abstractUnavailableReason", "a provider record without abstract needs a reason")
    return errors


def load(path: Path = RECORD) -> tuple[Record | None, list[str]]:
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as error:
        return None, [f"{path}: {error}"]
    try:
        record = Record.model_validate_json(text)
    except ValidationError as error:
        return None, [
            f"{'.'.join(str(part) for part in item['loc'])}: {item['msg']}"
            for item in error.errors()
        ]
    errors = [e for key, ref in record.references.items() for e in reference_errors(key, ref)]
    if not record.method.strip():
        errors.append("method: is empty")
    return record, errors


def citations(files: Iterable[Path]) -> list[tuple[str, Path, int]]:
    """(key, file, line) of every cited key, in file and line order, comments removed."""
    found = []
    for path in files:
        text = "\n".join(COMMENT.sub("", line) for line in path.read_text("utf-8").splitlines())
        for match in CITE.finditer(text):
            line = text.count("\n", 0, match.start()) + 1
            for key in match.group(1).split(","):
                if key.strip():
                    found.append((key.strip(), path, line))
    return found


def manuscript_files(paper: Path = PAPER) -> list[Path]:
    return sorted(p for p in paper.rglob("*.tex") if "generated" not in p.relative_to(paper).parts)


def entry(key: str, ref: Reference) -> str:
    lines = [f"@{ref.entryType}{{{key},"]
    names = [name for name in FIELD_ORDER if name in ref.fields]
    for name in names:
        lines.append(f"  {name} = {{{ref.fields[name]}}},")
    lines.append("}")
    return "\n".join(lines)


def bib_text(record: Record, cited: Sequence[tuple[str, Path, int]]) -> tuple[str, list[str]]:
    errors = []
    keys = sorted({key for key, _, _ in cited})
    for key, path, line in cited:
        ref = record.references.get(key)
        if ref is None:
            errors.append(f"{path.name}:{line}: cited key {key} has no record")
        elif ref.status != "verified":
            errors.append(f"{path.name}:{line}: cited key {key} is {ref.status}")
    body = [entry(key, record.references[key]) for key in keys if key in record.references]
    return "\n\n".join([BIB_HEADER, *body]) + "\n", errors


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Validate the reference record; write refs.bib.")
    parser.add_argument("command", choices=("check", "bib"))
    parser.add_argument("--record", type=Path, default=RECORD)
    parser.add_argument("--out", type=Path, default=BIB)
    parser.add_argument("--paper", type=Path, default=PAPER)
    args = parser.parse_args(argv)
    record, errors = load(args.record)
    if record is not None and args.command == "bib":
        text, bib_errors = bib_text(record, citations(manuscript_files(args.paper)))
        errors += bib_errors
        if not errors:
            args.out.write_bytes(text.encode("utf-8"))
    for error in errors:
        print(f"references.py: {error}", file=sys.stderr)
    if errors:
        print(f"references.py: {len(errors)} errors", file=sys.stderr)
        return 1
    assert record is not None
    verified = sum(ref.status == "verified" for ref in record.references.values())
    print(
        f"references.py: {len(record.references)} records, {verified} verified; {args.command} ok"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
