"""Write generated pgfplots data for the paper from committed artifacts (PRD 22.5, 22.6).

generated/distance-plot.tex holds the \\addplot commands of the candidate distance figure: the
relief and texture distances of every compared Earth window to the lunar target, read from
outputs/comparisons/<target_id>.json, one plot per search region, plus the shortlist from
outputs/search/targets.json. A distance that is not available is left out of the plot and
counted in a comment line, never drawn as 0. The output is deterministic.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
ROOT = PAPER.parent
OUT = PAPER / "generated" / "distance-plot.tex"
# One plot file per search target: (target_id, output file stem).
TARGETS = (
    ("moon-cr-site01-w000", "distance-plot"),
    ("mars-jezero-w000", "distance-plot-jezero"),
    ("mars-arcadia-w000", "distance-plot-arcadia"),
)
HEADER = "% Generated by paper/scripts/tables.py. Do not edit; run make -C paper tables."
REGIONS = (
    ("utm27n", "Holuhraun", "okvermilion, mark=square*"),
    ("utm11n", "Rosamond Dry Lake", "okgreen, mark=triangle*"),
)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def distance_plot(root: Path = ROOT, target_id: str = TARGETS[0][0]) -> str:
    targets_path = root / "outputs" / "search" / "targets.json"
    targets = json.loads(targets_path.read_text("utf-8"))
    matching = [t for t in targets if t["target_id"] == target_id]
    if len(matching) != 1:
        raise ValueError(f"{len(matching)} targets named {target_id} in {targets_path}")
    target = matching[0]
    comparisons_path = root / "outputs" / "comparisons" / f"{target['target_id']}.json"
    records = json.loads(comparisons_path.read_text("utf-8"))
    shortlist = set(target["shortlist"]["earth_window_ids"])
    lines = [
        HEADER,
        f"% Source: {comparisons_path.relative_to(root)} sha256 {sha256(comparisons_path)}.",
        f"% Source: {targets_path.relative_to(root)} sha256 {sha256(targets_path)}.",
    ]
    points: dict[str, list[tuple[float, float, str]]] = {key: [] for key, _, _ in REGIONS}
    missing = 0
    for record in sorted(records, key=lambda r: str(r["earth_window_id"])):
        families = record["distances_by_family"]
        relief = families["terrain_relief"]["value"]
        texture = families["terrain_texture"]["value"]
        window = str(record["earth_window_id"])
        region = window.split("-")[1]
        if relief is None or texture is None or region not in points:
            missing += 1
            continue
        points[region].append((float(relief), float(texture), window))
    lines.append(f"% Windows without both distances, left out: {missing}.")
    order = ", ".join(name for _, name, _ in REGIONS)
    lines.append(f"% Plot order: {order}, first Pareto layer.")
    for key, _name, style in REGIONS:
        coords = " ".join(f"({r:.4f},{t:.4f})" for r, t, _ in points[key])
        lines.append(f"\\addplot[only marks, {style}, mark size=1.6pt] coordinates {{{coords}}};")
    best = [p for key in points for p in points[key] if p[2] in shortlist]
    coords = " ".join(f"({r:.4f},{t:.4f})" for r, t, _ in best)
    lines.append(
        f"\\addplot[only marks, mark=o, mark size=4pt, thick, black] coordinates {{{coords}}};"
    )
    return "\n".join(lines) + "\n"


def main() -> int:
    for target_id, stem in TARGETS:
        out = PAPER / "generated" / f"{stem}.tex"
        out.write_bytes(distance_plot(ROOT, target_id).encode("utf-8"))
        print(f"tables.py: wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
